USES = {s[0]: s[4] for s in SECTIONS}
def ancestors(slug, memo={}):
    if slug in memo: return memo[slug]
    a = set()
    for u in USES[slug]:
        a.add(u); a |= ancestors(u)
    memo[slug] = a
    return a
def _reduced(slug):
    out = []
    for u in USES[slug]:
        others = set()
        for v in USES[slug]:
            if v != u: others |= ancestors(v)
        if u not in others: out.append(u)
    return out
